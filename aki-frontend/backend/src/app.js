const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const morgan = require('morgan');
const health = require('./routes/health');
const catalog = require('./routes/catalog');
const orders = require('./routes/orders');
const users = require('./routes/users');
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CORS_ORIGIN || '*' }));
app.use(express.json({ limit: '1mb' }));
app.use(morgan('dev'));
app.get('/', (_req, res) => res.json({ name: 'AKI Delivery API', status: 'online', integratedWithFrontend: false }));
app.use('/api/v1/health', health);
app.use('/api/v1/catalog', catalog);
app.use('/api/v1/orders', orders);
app.use('/api/v1/users', users);
app.use((req, res) => res.status(404).json({ error: 'Rota não encontrada.' }));
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ error: 'Erro interno da API.' }); });
module.exports = app;
